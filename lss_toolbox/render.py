"""``docs/TOOLS.md``: the catalogue rendered as a page (one table per menu,
then every item with its command lines and documented variations).
Written by ``python -m lss_toolbox --render``; ``tests/test_toolbox.py``
fails when the page differs from the rendering, so the page, the menu and
the scripts cannot drift apart. Deterministic: nothing here depends on git
or on the machine (staleness is shown live by the window and by
``python -m lss_toolbox --stale``)."""
import os
import shlex

from . import ROOT
from . import catalog, texts

PAGE = os.path.join(ROOT, 'docs', 'TOOLS.md')

HEADER = """# Tools: every demonstration and figure generator

Generated by `python -m lss_toolbox --render` from `lss_toolbox/catalog.py`;
do not edit by hand (`tests/test_toolbox.py` fails when this page and the
catalogue differ). The same catalogue builds the reader's **Tools** menu and
the Tools window (`python -m lss_toolbox`, or Tools > All tools… in the
reader), so this page, the menu and the scripts cannot drift apart.

How it stays current (owner, 2026-11-23: "built from what's in the repo and
so don't drift"):

- every run executes the repository's script as it is now, into a folder of
  its own (`~/.lss_reader/tools/<item>/<date-time>`, or
  `$LSS_READER_TOOLS_DIR`), with a `run.json` naming the command and the git
  commit; nothing is written into the repository unless asked (Tools window:
  "Replace the committed products", only with the settings that made them,
  usually the defaults);
- the options a page offers are read from the script's own argparse parser
  each time (`lss_toolbox.introspect`), never copied;
- `python -m lss_toolbox --audit` reruns every item with the settings that
  made its committed products and compares: images pixel for pixel, tables
  and text apart from how they were run (the command line they echo, their
  timings, the lines an item names as `volatile`), and a figure that prints
  its git revision apart from that stamp (found by a second run with a dummy
  revision, `LSS_TOOLS_REVISION`). This is the measured staleness; the last
  audit is `docs/reports/tools_audit.md`. With `--record` it keeps, for each item
  whose products matched, the fingerprints of the modules the run actually
  imported, the files it read and the products it reproduced, in
  `lss_toolbox/verified.json`;
- an item's committed products are **current** while that record holds:
  nothing the rerun used has changed since. A fingerprint of Python code
  ignores docstrings and comments (`lss_toolbox.fingerprint`). Without a
  record, or after the products changed, they are flagged **possibly
  stale** when the script, a repository file it imports, or a named input
  changed its code after the products' last commit (`lss_toolbox.staleness`;
  `python -m lss_toolbox --stale` lists them all);
- the tests check that every script in `tests/tools/` is an item (or a
  listed helper), that every option a variation sets exists in its script,
  and that every figure committed under `docs/` belongs to an item.

A **variation** is a change of settings the documents describe ("change
this parameter and regenerate the figure to see that"), with the document
line it comes from. In the Tools window, choosing one fills the form; Run
makes the figure. Here each is written as the command line it runs.
`{out}` is the run's folder. Times were measured in the development
container on 2026-11-23 with the defaults shown.
"""

DATA = {
    'synthetic': 'synthetic (public)',
    'public': 'public (NX school or committed tables)',
    'any': 'NX school by default; any SPEC file',
    'private': 'private (not in the repository)',
}


def _cell(s):
    return str(s).replace('|', '\\|').replace('\n', ' ')


def _args_text(args):
    out = []
    for k, v in args.items():
        if v is True:
            out.append(k)
        elif v is False or v == '':
            continue
        elif isinstance(v, (list, tuple)):
            for x in v:
                out += [k, shlex.quote(str(x))]
        elif k.startswith('-'):
            out += ['%s=%s' % (k, shlex.quote(str(v)))] if str(v).startswith('-') else [k, shlex.quote(str(v))]
        else:
            out.append(shlex.quote(str(v)))
    return ' '.join(out)


def command(tool, args=None):
    """The command line of ``tool`` with its defaults updated by ``args``
    (as the catalogue writes them)."""
    merged = dict(tool.defaults)
    merged.update(args or {})
    text = _args_text(merged)
    if tool.subcommand:
        text = (tool.subcommand + ' ' + text).strip()
    if tool.free and 'free' not in (args or {}):
        text = (text + ' ' + tool.free).strip()
    return ('python %s %s' % (tool.script, text)).strip()


def _time(t):
    if t.seconds is None:
        return ''
    return '%.0f s' % t.seconds if t.seconds >= 1 else '< 1 s'


def page():
    lines = [HEADER]
    lines.append('## Menus\n')
    for cat, name in catalog.CATEGORIES:
        items = catalog.in_category(cat)
        if not items:
            continue
        lines.append('### %s\n' % name)
        lines.append('| Item | Kind | What it demonstrates | Data | Time | Committed products |')
        lines.append('|---|---|---|---|---|---|')
        for t in items:
            lines.append('| [%s](#%s) | %s | %s | %s | %s | %s |' % (
                _cell(t.title), t.id.replace('_', '-'), t.kind, _cell(t.demonstrates), DATA.get(t.data, t.data),
                _time(t), '<br>'.join('`%s`' % c for c in t.committed) or '—'))
        lines.append('')
    lines.append('## Items\n')
    for cat, name in catalog.CATEGORIES:
        for t in catalog.in_category(cat):
            lines.append('<a id="%s"></a>\n' % t.id.replace('_', '-'))
            lines.append('### %s\n' % t.title)
            lines.append('%s\n' % t.demonstrates)
            facts = ['Menu: Tools > %s' % name, 'kind: %s (%s)' % (t.kind, catalog.KINDS[t.kind])]
            if t.script:
                facts.append('script: `%s`' % t.script)
            lines.append('- ' + '; '.join(facts))
            if t.docs:
                lines.append('- Explained in: ' + ', '.join('`%s`' % d for d in t.docs))
            if t.committed:
                how = ('replaced from the window with the settings that made them (into `%s`)' % t.repo_out
                       if t.repo_out else 'replaced from the window with the settings that made them') \
                    if t.repo_ok else 'not replaced from the window'
                lines.append('- Committed products: %s; %s' % (', '.join('`%s`' % c for c in t.committed), how))
            if t.runnable:
                lines.append('- Run:\n\n      %s\n' % command(t))
            if t.committed_with:
                lines.append('- The committed products were made with:\n\n      %s\n' % command(t, t.committed_with))
            if t.variations:
                lines.append('Variations:\n')
                lines.append('| Variation | Shows | Source | Command |')
                lines.append('|---|---|---|---|')
                for v in t.variations:
                    lines.append('| %s | %s | `%s` | `%s` |' % (_cell(v.label), _cell(v.shows), v.source,
                                                             _cell(command(t, v.args))))
                lines.append('')
            else:
                lines.append('')
    lines.append('## The Tools window\n')
    lines.append('Opened from the reader (Tools > All tools…, or any item) or on its own '
                 '(`python -m lss_toolbox [--item ID]`). Left: the items by menu; right: the chosen item\'s page '
                 '(made when first shown). Labels and tooltips, from `lss_toolbox/texts.py`:\n')
    lines.append('| Control | Label | Tooltip |')
    lines.append('|---|---|---|')
    for name, label, tip in texts.CONTROLS:
        lines.append('| `%s` | %s | %s |' % (name, _cell(label) or '—', _cell(tip)))
    lines.append('')
    lines.append('## Helpers (not items)\n')
    for name, what in sorted(catalog.HELPERS.items()):
        lines.append('- `tests/tools/%s`: %s' % (name, what))
    lines.append('')
    return '\n'.join(lines)


def write(path=PAGE):
    text = page()
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    return path
