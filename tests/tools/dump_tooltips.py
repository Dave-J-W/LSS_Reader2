"""Every control of the window and its dialogs, with its tooltip, as
Markdown: raw material for the manual (owner, 2026-11-19: breadcrumbs for
the manual writer). The window keeps explanations in tooltips (AGENTS.md
rule 9), so this is where most of the "why" is.

    python tests/tools/dump_tooltips.py > docs/manual/controls.md

Run from the repository root. Opens no data; needs no display. Controls
created only when data are loaded (some result panes) are not listed.
"""
import os
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
os.chdir(ROOT)
sys.path.insert(0, ROOT)
os.environ.setdefault('QT_QPA_PLATFORM', 'offscreen')
os.environ.setdefault('MPLBACKEND', 'Agg')
os.environ['LSS_READER_LOG_DIR'] = tempfile.mkdtemp(prefix='lss_tooltips_logs_')
os.environ['LSS_READER_PREFS'] = os.path.join(tempfile.mkdtemp(prefix='lss_tooltips_prefs_'), 'p.json')


def _where(w, stop):
    """Tab titles and group-box titles from ``stop`` down to ``w``."""
    from PyQt5.QtWidgets import QTabWidget, QGroupBox, QStackedWidget
    parts, child, p = [], w, w.parentWidget()
    while p is not None and child is not stop:
        if isinstance(p, QStackedWidget) and isinstance(p.parentWidget(), QTabWidget):
            tabs = p.parentWidget()
            i = tabs.indexOf(child)
            if i >= 0:
                parts.append(tabs.tabText(i).replace('&', ''))
        elif isinstance(p, QGroupBox) and p.title():
            parts.append(p.title())
        child, p = p, p.parentWidget()
    return ' > '.join(reversed(parts))


def _label(w):
    for name in ('text', 'title', 'windowTitle'):
        f = getattr(w, name, None)
        if callable(f):
            try:
                t = f()
            except TypeError:
                continue
            if isinstance(t, str) and t:
                return t.replace('&', '')
    return ''


def rows(top, title):
    from PyQt5.QtWidgets import QWidget
    out = []
    for w in [top] + top.findChildren(QWidget):
        tip = w.toolTip()
        if not tip and not w.objectName().endswith(('CheckBox', 'PushButton', 'ComboBox', 'LineEdit', 'SpinBox')):
            continue
        out.append((title, _where(w, top), w.objectName(), type(w).__name__, _label(w), tip))
    return out


def main():
    from PyQt5.QtWidgets import QApplication
    app = QApplication.instance() or QApplication(['lss-tooltips'])
    sys.excepthook = lambda *a: None
    from mainwindow import MainWindow
    w = MainWindow()
    found = rows(w, 'Main window')
    for build, title in ((w.buildPreferences, 'Preferences'), (w.buildGIDWorksheet, 'GID worksheet'),
                         (w.buildBurnDialog, 'Burn test'), (w.showPlotOptions, 'Plot options')):
        try:
            d = build()
        except Exception as e:                       # report, do not stop
            found.append((title, '', '', '', '(could not be built: %s)' % e, ''))
            continue
        if d is not None:
            found += rows(d, title)
    for a in w.findChildren(__import__('PyQt5.QtWidgets', fromlist=['QAction']).QAction):
        if a.text() and a.toolTip() and a.toolTip().replace('&', '') != a.text().replace('&', ''):
            found.append(('Menus', '', a.objectName(), 'QAction', a.text().replace('&', ''), a.toolTip()))
    clean = lambda s: str(s).replace('|', '\\|').replace('\n', ' ')
    print('# Controls and their tooltips\n')
    print('Generated by `python tests/tools/dump_tooltips.py`; do not edit by hand. '
          'Controls without a tooltip are listed so that the gaps show.\n')
    print('| Window | Where | Object | Kind | Label | Tooltip |\n|---|---|---|---|---|---|')
    for r in found:
        print('| ' + ' | '.join(clean(x) for x in r) + ' |')
    tipped = sum(1 for r in found if r[5])
    print('\n%d controls listed, %d with a tooltip.' % (len(found), tipped))
    w.close()
    app.processEvents()


if __name__ == '__main__':
    main()
